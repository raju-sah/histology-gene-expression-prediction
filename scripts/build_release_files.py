def build_author_checklist(macros: dict[str, str]) -> Path:
    keys = set(re.findall(r"\{(\w+)\}", CHECKLIST))
    missing = sorted(k for k in keys if k not in macros)
    if missing:
        raise KeyError(f"macros missing from numbers.tex: {missing}")
    CHECKLIST_MD.write_text(re.sub(r"\{(\w+)\}", lambda m: macros[m.group(1)], CHECKLIST))
    print(f"Wrote {CHECKLIST_MD}")
    return CHECKLIST_MD


def sync_arxiv_package():
    ARXIV_DIR.mkdir(parents=True, exist_ok=True)
    # figures live next to main.tex in the package, not in ../reports
    (ARXIV_DIR / "main.tex").write_text(MAIN_TEX.read_text().replace("../reports/", "reports/"))
    shutil.copy(ROOT / "paper" / "refs.bib", ARXIV_DIR / "refs.bib")
    shutil.copytree(ROOT / "paper" / "generated", ARXIV_DIR / "generated", dirs_exist_ok=True)
    fig_dir = ARXIV_DIR / "reports" / "phase2" / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    for p in (ROOT / "reports" / "phase2" / "figures").glob("*.png"):
        shutil.copy(p, fig_dir / p.name)
    print(f"Synced arXiv package in {ARXIV_DIR}")


def main():
    macros = load_macros()
    build_biorxiv_metadata(macros)
    build_author_checklist(macros)
    sync_arxiv_package()
    print("All release files built successfully.")


if __name__ == "__main__":
    main()
