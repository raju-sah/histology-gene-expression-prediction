NUMBERS_TEX = ROOT / "paper" / "generated" / "numbers.tex"
CHECKLIST_MD = ROOT / "paper" / "AUTHOR_CHECKLIST.md"
BIORXIV_DIR = ROOT / "release" / "biorxiv"
ARXIV_DIR = ROOT / "release" / "arxiv"
TITLE = ("Which genes can a pathology foundation model see? "
         "Cellularity confounding and transcriptome-wide predictability from H&E")


def load_macros() -> dict[str, str]:
    if not NUMBERS_TEX.exists():
        raise FileNotFoundError(f"{NUMBERS_TEX} does not exist. Run scripts/make_paper_numbers.py first.")
    return dict(re.findall(r"\\newcommand\{\\(\w+)\}\{([^}]*)\}", NUMBERS_TEX.read_text()))


def expand(tex: str, macros: dict[str, str]) -> str:
    """\\num{X} -> value; raises KeyError if a macro is missing."""
    return re.sub(r"\\num\{(\w+)\}", lambda m: macros[m.group(1)], tex)


def tex_to_plain(tex: str) -> str:
    s = tex
    for a, b in [(r"\text{count}", "count"), (r"\text{lognorm}", "lognorm"), (r"\text{log1p}", "log1p"),
                 (r"\log", "log"), (r"H\&E", "H&E"), (r"\%", "%"), (r"\sim", "~"), ("{,}", ","),
                 ("$", ""), ("R^2", "R^2")]:
        s = s.replace(a, b)
    return re.sub(r"\s+", " ", s).strip()


def paper_abstract(macros: dict[str, str]) -> str:
    m = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", MAIN_TEX.read_text(), re.S)
    return tex_to_plain(expand(m.group(1), macros))


