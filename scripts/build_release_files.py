"""Build the release files from the paper and the generated macros (no hand-typed numbers).

    .venv/bin/python scripts/build_release_files.py

- release/biorxiv/metadata.json: the abstract is taken from paper/main.tex with every \\num{...} expanded.
- paper/AUTHOR_CHECKLIST.md: regenerated from the template below; a missing macro raises an error.
- release/arxiv/: main.tex, refs.bib, generated/ and figures, with figure paths made local to the package.
"""
from __future__ import annotations

import json
import re
